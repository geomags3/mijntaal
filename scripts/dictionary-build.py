"""Build a pinned, source-preserving SQLite dictionary and static bilingual overlays.

Inputs are local files; this command never downloads data or touches personal databases.
See docs/DICTIONARY.md for acquisition and explicit regeneration.
"""

import argparse
import collections
import hashlib
import json
import pathlib
import re
import shutil
import sqlite3
import tempfile
import unicodedata
from urllib.parse import quote


def normal(value):
    return unicodedata.normalize("NFC", value).strip().lower()


def encoded(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True)


def checksum(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def tree_checksum(path):
    digest = hashlib.sha256()
    for file in sorted(path.glob("*.json")):
        digest.update(file.name.encode() + b"\0" + bytes.fromhex(checksum(file)))
    return digest.hexdigest()


def bucket(word):
    value = 2166136261
    for byte in word.encode():
        value = ((value ^ byte) * 16777619) & 0xFFFFFFFF
    return f"{value % 256:02x}"


def write_json(path, value):
    path.write_text(encoded(value) + "\n", encoding="utf-8")


def pos_from_entry(value):
    match = re.search(r"__([^_]+)__\d+$", value or "")
    pos = match.group(1).lower() if match else ""
    return {"propernoun": "name", "proper noun": "name"}.get(pos, pos)


def build(lock, root, kaikki_dir, wikdict_dir, database, output):
    if lock.get("schemaVersion") != 1:
        raise ValueError("Unsupported dictionary source lock version")
    source = lock["kaikki"]
    if source["format"] != "mijntaal-v1":
        raise ValueError("Unsupported Kaikki source adapter")
    if tree_checksum(kaikki_dir) != source["sha256"]:
        raise ValueError("Kaikki source checksum mismatch; use the pinned snapshot")
    inputs = []
    for item in lock["wikdict"]:
        if item["format"] != "wikdict-sqlite-v2":
            raise ValueError("Unsupported bilingual source adapter")
        languages = item["languages"]
        if languages not in [["nl", "en"], ["en", "nl"]]:
            raise ValueError("This export supports Dutch and English only")
        path = wikdict_dir / item["filename"]
        if checksum(path) != item["sha256"]:
            raise ValueError("WikDict source checksum mismatch: " + item["filename"])
        inputs.append((item, path))
    if output.resolve() == kaikki_dir.resolve() or kaikki_dir.resolve() in output.resolve().parents:
        raise ValueError("Output must not overwrite the source dictionary")
    if output.exists():
        manifest = output / "manifest.json"
        if not manifest.exists() or json.loads(manifest.read_text()).get("generator") != "mijntaal-dictionary-build-v1":
            raise ValueError("Refusing to replace an output directory not generated by this tool")
    database.parent.mkdir(parents=True, exist_ok=True)
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="mijntaal-dictionary-", dir=database.parent) as temporary:
        dbfile = pathlib.Path(temporary) / "dictionary.sqlite3"
        db = sqlite3.connect(dbfile)
        db.executescript("""
            CREATE TABLE sources(id TEXT PRIMARY KEY, metadata TEXT NOT NULL);
            CREATE TABLE entries(id TEXT PRIMARY KEY, language TEXT NOT NULL,
                normalized TEXT NOT NULL, spelling TEXT NOT NULL, pos TEXT NOT NULL,
                source TEXT NOT NULL REFERENCES sources(id), body TEXT NOT NULL);
            CREATE INDEX entries_lookup ON entries(language,normalized,pos);
            CREATE TABLE translations(id TEXT PRIMARY KEY, source TEXT NOT NULL REFERENCES sources(id),
                from_language TEXT NOT NULL, to_language TEXT NOT NULL, normalized TEXT NOT NULL,
                spelling TEXT NOT NULL, pos TEXT NOT NULL, sense TEXT NOT NULL,
                lexentry TEXT NOT NULL, sense_number TEXT NOT NULL, targets TEXT NOT NULL,
                score REAL NOT NULL, importance REAL NOT NULL, quality INTEGER);
            CREATE INDEX translations_lookup ON translations(from_language,to_language,normalized);
        """)
        for item in [source] + lock["wikdict"]:
            db.execute("INSERT INTO sources VALUES(?,?)", (item["id"], encoded(item)))
        entry_count = 0
        for file in sorted(kaikki_dir.glob("??.json")):
            rows = json.loads(file.read_text(encoding="utf-8"))
            for spelling, records in sorted(rows.items()):
                for index, record in enumerate(records):
                    body = encoded(record)
                    identifier = hashlib.sha256((source["id"] + "\0" + spelling + "\0" + str(index) + "\0" + body).encode()).hexdigest()
                    db.execute("INSERT INTO entries VALUES(?,?,?,?,?,?,?)", (identifier, "nl", normal(spelling), record["word"], record.get("pos", ""), source["id"], body))
                    entry_count += 1
        for item, path in inputs:
            connection = sqlite3.connect("file:" + quote(str(path.resolve())) + "?mode=ro", uri=True)
            try:
                for row in connection.execute("SELECT lexentry,sense_num,sense,written_rep,trans_list,score,importance,is_good FROM translation ORDER BY written_rep,lexentry,sense,trans_list"):
                    lexentry, number, sense, spelling, target_list, score, importance, quality = row
                    if not isinstance(spelling, str) or not isinstance(target_list, str):
                        continue
                    targets = list(dict.fromkeys(unicodedata.normalize("NFC", target.strip()) for target in target_list.split(" | ") if target.strip()))
                    if not targets or not normal(spelling):
                        continue
                    payload = [item["id"], *row[:4], targets]
                    identifier = hashlib.sha256(encoded(payload).encode()).hexdigest()
                    db.execute("INSERT OR IGNORE INTO translations VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?)", (identifier, item["id"], *item["languages"], normal(spelling), spelling, pos_from_entry(lexentry), sense or "", lexentry or "", str(number if number is not None else ""), encoded(targets), float(score or 0), float(importance or 0), quality))
            finally:
                connection.close()
        db.commit()
        with tempfile.TemporaryDirectory(prefix="dictionary-export-", dir=output.parent) as export_temp:
            staged = pathlib.Path(export_temp) / "v2"
            staged.mkdir()
            manifest = {"schemaVersion": 2, "generator": "mijntaal-dictionary-build-v1", "sourceLock": hashlib.sha256(encoded(lock).encode()).hexdigest(), "kaikkiBase": "/dictionary/v1/", "sources": [source] + lock["wikdict"], "languages": {}, "counts": {"kaikkiRecords": entry_count}}
            for language in ["nl", "en"]:
                shards = collections.defaultdict(dict)
                indexes = collections.defaultdict(list)
                records = collections.defaultdict(list)
                for row in db.execute("SELECT normalized,spelling,pos,sense,targets,source,lexentry,sense_number,score,importance FROM translations WHERE from_language=? ORDER BY normalized,score DESC,spelling,sense,targets", (language,)):
                    word, spelling, pos, sense, targets, origin, lexentry, sense_number, score, importance = row
                    records[word].append({"word": spelling, "pos": pos, "sense": sense, "targets": json.loads(targets), "source": origin, "lexentry": lexentry, "senseNumber": sense_number, "score": score})
                for word, values in sorted(records.items()):
                    # All source records remain in SQLite. Bound browser payloads for pathological entries.
                    chosen = values[:32]
                    shards[bucket(word)][word] = chosen
                    targets = list(dict.fromkeys(target for value in chosen for target in value["targets"]))
                    indexes[word[0]].append([values[0]["word"], "; ".join(targets)[:180], values[0]["pos"]])
                for number in range(256):
                    name = f"{language}-{number:02x}.json"
                    write_json(staged / name, shards[f"{number:02x}"])
                letters = {}
                for letter, values in sorted(indexes.items()):
                    name = language + "-index-" + letter.encode().hex() + ".json"
                    write_json(staged / name, values)
                    letters[letter] = name
                manifest["languages"][language] = {"words": len(records), "letters": letters}
            manifest["counts"]["translationRecords"] = db.execute("SELECT COUNT(*) FROM translations").fetchone()[0]
            manifest["files"] = {file.name: checksum(file) for file in sorted(staged.glob("*.json"))}
            write_json(staged / "manifest.json", manifest)
            if output.exists():
                shutil.rmtree(output)
            staged.rename(output)
        db.execute("PRAGMA optimize")
        db.close()
        dbfile.replace(database)
    return manifest["counts"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sources", type=pathlib.Path, default=pathlib.Path("scripts/dictionary-sources.json"))
    parser.add_argument("--root", type=pathlib.Path, default=pathlib.Path("."))
    parser.add_argument("--kaikki-dir", type=pathlib.Path)
    parser.add_argument("--wikdict-dir", type=pathlib.Path, required=True)
    parser.add_argument("--database", type=pathlib.Path, default=pathlib.Path(".dictionary/dictionary.sqlite3"))
    parser.add_argument("--output", type=pathlib.Path, default=pathlib.Path("public/dictionary/v2"))
    args = parser.parse_args()
    lock = json.loads(args.sources.read_text(encoding="utf-8"))
    kaikki_dir = args.kaikki_dir or args.root / lock["kaikki"]["path"]
    print(encoded(build(lock, args.root, kaikki_dir, args.wikdict_dir, args.database, args.output)))


if __name__ == "__main__":
    main()
